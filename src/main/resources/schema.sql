-- UUIDv7 primary keys on a table partitioned monthly by created_at.
--
-- The partition key must be part of every unique constraint, hence PRIMARY KEY (id, created_at).
-- Uniqueness of id alone is therefore only enforced per partition; UUIDv7 supplies global
-- uniqueness on its own.

CREATE TABLE IF NOT EXISTS payments (
    id           uuid        NOT NULL,
    created_at   timestamptz NOT NULL,
    amount_cents bigint      NOT NULL,
    currency     text        NOT NULL,
    reference    text        NOT NULL,
    status       text        NOT NULL,
    PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);

-- Bounds are written with an explicit UTC offset. Without one they would be interpreted in the
-- creating session's TimeZone, which silently shifts every boundary.
--
-- 2023-10 .. 2026-09 carry the benchmark data; 2026-10 .. 2026-12 are ahead of it so a POST
-- landing today has somewhere to go.

